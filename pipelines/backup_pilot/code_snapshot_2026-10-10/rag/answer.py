SYSTEM = """You answer a Korean question from regulatory-affairs staff using only the evidence pages given. All evidence comes from one document source (EMA, FDA, Health Canada, PMDA or sponsor documents) about one product.

Rules:
- Use only the evidence. No outside knowledge. Do not calculate anything (no new ratios, percentages, sums or conversions); copy numbers, units and confidence intervals exactly as written.
- Each page may include <candidate study context ...> markers generated by heuristics. These are unverified retrieval hints and may be wrong, including for negation, contextual comparisons and pooled analyses. Establish a value's study, analysis and comparison from the source text itself, including headings and surrounding text. Never reject or accept evidence solely because of a marker. The question is about the studies listed under "Studies asked".
- When the asked studies are "not specified", answer for each study the evidence covers and name the study in each item.
- Give exactly what is asked. A value only answers the question when it matches on every point the question sets: the analysis (primary, post-hoc, sensitivity, subgroup, pooled), the comparison (which product against which reference, e.g. CT-P43 vs EU-Stelara is not EU-Stelara vs US-Stelara), the analysis set (randomised, PK set, safety set), the parameter (AUCinf/AUC0-inf is not AUClast or AUC0-t), the statistic (ratio, confidence interval, geometric mean), the measure (ADA is not NAb; treatment-induced is not anytime), the arm and the timepoint. Inclusion criteria are not baseline characteristics or subgroup categories. A neighbouring value is never the answer.
- Tables may come out of the PDF with their cells listed one by one and columns out of order. Assign a number to a comparison, arm or column only when the text makes that certain; otherwise say the table cannot be read reliably.
- When the question asks per arm or per comparison, give every arm or comparison the evidence states, and say which ones it does not state.
- items: values from the evidence. value is copied verbatim and kept short. quote is one contiguous verbatim passage from a cited block containing the value and sufficient surrounding source text to support source_label and the study/analysis/comparison attribution. Do not use generated context markers as quotations. If the attribution cannot be established, omit the item. source_label says what the value is exactly as the source states it (parameter, statistic, comparison or arm, analysis, analysis set, timepoint as applicable). exact is true only when the value is exactly what the question asks; a related value given as context (e.g. AUClast when AUCinf was asked) has exact false. study is the registry key of the study the value belongs to (none for values about no particular study). evidence lists only the ids of the blocks that actually state the quote, e.g. ["E2"].
- status: answered when every part of the question is answered by exact values; partial when only some parts are, or when the evidence states the answer only in part (e.g. "healthy adult subjects" without age or weight limits); not_found when the evidence does not state it. Never guess a value.
- A conclusion (e.g. whether equivalence was shown) must follow the evidence's own statement or numbers, not be assumed.
- answer_ko: 2 to 5 Korean sentences that state only what was asked and what the evidence says. Name each value's comparison, arm and analysis as in source_label. When only related values exist, say first that the asked value is not stated, then give the related values labelled as such (e.g. "AUCinf는 없고, AUClast의 90% 신뢰구간만 있다"). No conclusions, interpretation or commentary the evidence does not state. Keep English abbreviations, numbers, units and study numbers as in the evidence; name studies as the evidence does (e.g. "Study CT-P43 1.2"), never by registry key. Put the block id after each value, like [E2]. If the answer is not found, say that the retrieved pages of this agency's documents do not state it; do not say that the document as a whole lacks it."""


class Corpus:
    """Chunks, vectors and BM25 for one embedding model, plus page texts."""

    def __init__(self, model="bge-m3", rag_dir=None, local_only=False, bundle=None, review_url='http://127.0.0.1:8766', include_nondefault=False):
        self.model = model
        self.local_only = local_only
        self.include_nondefault = include_nondefault
        self.chunks, self.vec, self.index_meta = load_index(model, rag_dir)
        self.evidence_adapter = None
        if bundle is not None:
            from rag.budgeted_evidence import BudgetedEvidence
            self.evidence_adapter = BudgetedEvidence(bundle, self.chunks, self.index_meta['chunks_sha256'], review_url)
        self.documents = {(d["document_id"], d["version_id"]): d for d in
                          (json.loads(line) for line in (ROOT / "data/catalog/documents.jsonl").read_text(encoding="utf-8").splitlines() if line.strip())}
        self.bm = Bm25(self.chunks)
        self._emb = None
        self.allowed_documents = None
        self.by_page = {}
        eligible = set(filter_idx(self.chunks,include_nondefault=include_nondefault))
        for i, c in enumerate(self.chunks):
            doc = self.documents.get((c["document_id"], c.get("version_id")), {})
            c.setdefault("source_url", doc.get("final_url") or doc.get("url"))
            if i in eligible:
                self.by_page.setdefault((c["document_id"], c.get("version_id"), c["pdf_page"]), []).append(i)

    def encode(self, queries):
        if self._emb is None:
            self._emb = Embedder(self.model, local_only=self.local_only)
        return self._emb.encode_queries(queries)

    def release_encoder(self):
        self._emb = None
        import gc
        import torch
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    def page_text(self, doc, page, qv=None, version_id=None):
        """The page's chunks in order without their overlaps, with a marker wherever the study changes.

        A page longer than PAGE_CHARS (Health Canada pages hold a whole section, up to 15,000 characters)
        keeps the chunks closest to the query vector qv, in page order, with "[...]" where chunks are left
        out. Without qv the start of the page is kept.
        """
        if version_id is None:
            versions = {v for d, v, p in self.by_page if d == doc and p == page}
            if len(versions) > 1:
                raise ValueError("Page has multiple document versions; version_id is required")
            version_id = next(iter(versions), None)
        ids = self.by_page.get((doc, version_id, page), [])
        keep = set(ids)
        if sum(len(self.chunks[i]["text"]) for i in ids) > PAGE_CHARS:
            keep, size = set(), 0
            order = sorted(ids, key=lambda i: -float(self.vec[i] @ qv)) if qv is not None else ids
            for i in order:
                if size + len(self.chunks[i]["text"]) > PAGE_CHARS and keep:
                    continue
                keep.add(i)
                size += len(self.chunks[i]["text"])
        out, prev_label, prev_text, prev_kept = [], None, "", True
        for i in ids:
            if i not in keep:
                if prev_kept:
                    out.append("[...]")
                prev_kept, prev_text = False, ""
                continue
            c = self.chunks[i]
            text = c["text"]
            # New builds declare overlap; historical builds use the text heuristic.
            if "chunking" not in c or c["chunking"]["overlap_tokens"]:
                for n in range(min(len(prev_text), len(text), 1200), 20, -1):
                    if prev_text.endswith(text[:n]):
                        text = text[n:]
                        break
            label = c.get("study_label") or "unknown"
            if label != prev_label:
                out.append(f"<candidate study context (heuristic, unverified): {label}>")
                prev_label = label
            out.append(text.strip())
            prev_text, prev_kept = c["text"], True
        s = "\n".join(x for x in out if x)
        # PAGE_CHARS is a selection budget. Never clip a selected table or its
        # footnote at an arbitrary character position; one whole chunk may exceed it.
        return s


def retrieve(corpus, u, qv, use_dense=True, k=TOP_PAGES, policy="legacy", agencies=None, products=None):
    """[(unit, pages)] for an understanding result; pages as rag/search.py to_pages."""
    out = []
    for unit in plan(u, **({'agencies': agencies} if agencies is not None else {}), products=products):
        unit = {**unit, "retrieval_policy": policy}
        if policy == "legacy":
            idx = filter_idx(corpus.chunks, unit["product"], unit["doc_groups"], unit["jurisdiction"],include_nondefault=getattr(corpus,'include_nondefault',False))
            idx = [i for i in idx if corpus.chunks[i]['product_id']==unit['product'] and corpus.chunks[i]['jurisdiction']==unit['jurisdiction']]
            if getattr(corpus,'allowed_documents',None) is not None:
                idx = [i for i in idx if (corpus.chunks[i]['document_id'],corpus.chunks[i].get('version_id')) in corpus.allowed_documents]
            pages = study_search.search(qv, u["search_terms"], idx, corpus.chunks, corpus.vec, corpus.bm,
                                        unit["studies"], "B", k=k, use_dense=use_dense) if len(idx) else []
            out.append((unit, pages))
            continue
        if policy != "general":
            raise ValueError(f"Unknown retrieval policy: {policy}")
        # Product and agency are evidence boundaries. Document groups are preferences, not exclusions.
        idx = filter_idx(corpus.chunks, unit["product"], None, unit["jurisdiction"],include_nondefault=getattr(corpus,'include_nondefault',False))
        idx = [i for i in idx if corpus.chunks[i]['product_id']==unit['product'] and corpus.chunks[i]['jurisdiction']==unit['jurisdiction']]
        if getattr(corpus,'allowed_documents',None) is not None:
            idx = [i for i in idx if (corpus.chunks[i]['document_id'],corpus.chunks[i].get('version_id')) in corpus.allowed_documents]
        if len(idx):
            hits = study_search.adaptive_hits(qv, u["search_terms"]+' '+u.get('english_query',''), idx, corpus.chunks, corpus.vec,
                                             corpus.bm, unit["studies"], unit["doc_groups"], use_dense,topic=unit.get('topic'))
            pages = to_pages(hits, corpus.chunks, k)
            query=u['search_terms']+' '+u.get('english_query','')
            from rag.regulatory_scope import requests_marketing_notification
            cue=('printed_requested_marketing_notification' if requests_marketing_notification(query) else
                 'printed_requested_indications' if re.search(r'indication',query,re.I) and re.search(r'pediatric|paediatric|children',query,re.I) else None)
            if cue:
                from rag.clinical_retrieval import rank as clinical_rank,cues
                direct=[(s,i) for s,i in clinical_rank(query,idx,corpus.chunks,unit['studies'],unit.get('topic'))
                    if cue in cues(query,corpus.chunks[i],unit['studies'],unit.get('topic'))]
                preferred=[(s,i) for s,i in direct if corpus.chunks[i]['doc_group'] in unit['doc_groups']]
                from rag.regulatory_scope import requests_approval_letter,approval_source
                if requests_approval_letter(query):
                    direct=[(s,i) for s,i in direct if approval_source(corpus.chunks[i])]
                    preferred=[(s,i) for s,i in preferred if approval_source(corpus.chunks[i])]
                if preferred or direct:
                    probe=to_pages(preferred or direct,corpus.chunks,1)
                    identities={(p['document_id'],p['version_id'],p['pdf_page']) for p in probe}
                    pages=[*probe,*[p for p in pages if (p['document_id'],p['version_id'],p['pdf_page']) not in identities]][:k]
            if unit['studies'] and re.search(r'\b\d+(?:\.\d+)?\s*mg\b',query,re.I) and re.search(r'GMR|geometric.*ratio|기하평균비',query,re.I):
                from rag.clinical_retrieval import rank as clinical_rank,cues
                dose=[(s,i) for s,i in clinical_rank(query,idx,corpus.chunks,unit['studies'],'dosing')
                    if 'printed_dose_and_administration' in cues(query,corpus.chunks[i],unit['studies'],'dosing')]
                if dose:
                    probe=to_pages(dose,corpus.chunks,1)
                    identities={(p['document_id'],p['version_id'],p['pdf_page']) for p in probe}
                    pages=[*probe,*[p for p in pages if (p['document_id'],p['version_id'],p['pdf_page']) not in identities]][:k]
        else:
            pages = []
        out.append((unit, pages))
    return out


def _studies_line(unit):
    if not unit["studies"]:
        return "not specified"
    reg = sr.load()
    lines = []
    for k in unit["studies"]:
        s = reg[k]
        desc = "; ".join(x for x in (s.get("population", ""), s.get("purpose", "")) if x)
        lines.append(f"{k} = {study_context.label([k])}" + (f" ({desc})" if desc else ""))
    return "; ".join(lines)


def messages_for(question, u, unit, pages, texts):
    prod = sr.products().get(unit["product"], {'names':[str(unit['product'] or '미상')]})
    blocks = []
    for n, (p, text) in enumerate(zip(pages, texts), 1):
        blocks.append(f"[E{n}] {p['title']}, p.{p['pdf_page']} ({p['document_type']})\n{text}")
    user = (f"Question (Korean): {question}\n"
            f"English rendering: {u['english_query']}\n"
            f"Agency: {AGENCY.get(unit['jurisdiction'],'미상')} ({unit['jurisdiction']})\n"
            f"Product: {unit['product']} ({', '.join(prod['names'])})\n"
            f"Studies asked: {_studies_line(unit)}\n\n"
            "Evidence:\n\n" + ("\n\n".join(blocks) if blocks else "(no pages retrieved)"))
    return [{"role": "system", "content": SYSTEM}, {"role": "user", "content": user}]


def cache_path(provider=None):
    s = settings(provider)
    name = re.sub(r"[^A-Za-z0-9.]+", "-", f"{s['provider']}_{s['model']}")
    return ROOT / "data/rag/cache" / f"answers_{PROMPT_VERSION}_{name}.json"


def validate_answer(out, evidence, allow_table_cells=False):
    """Check cited blocks and literal quotations; semantic attribution still needs evaluation."""
    kept, rejected = [], []
    for item in out["items"]:
        cited = item["evidence"]
        quote = item.get("quote", "")
        literal=contains_value(quote,item['value'])
        cell_matches=[]
        if allow_table_cells and not literal:
            from rag.table_evidence import matching_cells
            cell_matches=matching_cells(quote,item['value'])
        valid = (bool(cited) and item["study"] in {*sr.load(), NO_STUDY}
                 and all(e in evidence and contains_quote(evidence[e]["text"], quote) for e in cited)
                 and (literal or bool(cell_matches))
                 and "<candidate study context" not in quote and '[UNSUPPLIED SOURCE GAP]' not in quote)
        if valid and cell_matches:
            item={**item,'value_validation':{'method':'within_single_html_cell',
                'quote_relative_cells':[{k:c[k] for k in ('row','column','content_start','content_end','raw','value','rowspan','colspan')} for c in cell_matches],
                'semantic_approval':False}}
        (kept if valid else rejected).append(item)
    result = {**out, "items": kept, "validation": {"check": "literal_quote_and_citation", "rejected_items": rejected}}
    bad_prose_citations = [e for e in re.findall(r"\bE\d+\b", out["answer_ko"]) if e not in evidence]
    result["validation"]["invalid_prose_citations"] = bad_prose_citations
    if rejected or bad_prose_citations or (out["status"] != "not_found" and not kept):
        # Do not leave rejected values in the model's prose.
        result["status"] = "partial" if any(it["exact"] for it in kept) else "not_found"
        result["answer_ko"] = "인용 원문 검증을 통과하지 못한 항목을 제외했다."
        for it in kept:
            kind = "" if it["exact"] else " (관련 값)"
            result["answer_ko"] += f"\n{it['source_label']}{kind}: {it['value']} [{', '.join(it['evidence'])}]"
        if not kept:
            result["answer_ko"] += " 검색된 근거에서 검증 가능한 답을 확보하지 못했다."
    return result


def answer_unit(question, u, unit, pages, corpus, cache=None, qv=None, provider=None, chat_client=None):
    """One agency x product unit. Cached by prompt version, question, unit, evidence pages and their texts."""
    adapter = getattr(corpus, 'evidence_adapter', None)
    if adapter is not None:
        from rag.preprocessed_evidence import EXTRA_RULES, PROMPT_VERSION as PREPROCESSED_PROMPT_VERSION, grounded_answer, validate_shape
        from rag.preprocessed_prompt import build as build_prompt, configure_budget
        from rag.answer_conditions import quote_schema as condition_schema, QUOTE_RULES as CONDITION_RULES, missing as missing_conditions, label as condition_label
        selecting=bool(getattr(chat_client,'source_selection',False))
        from rag import source_selection
        make_messages=lambda blocks:build_prompt(question,u,unit,blocks,EXTRA_RULES,CONDITION_RULES)
        if selecting:make_messages=lambda blocks:source_selection.prompt(question,u,unit,blocks)
        if chat_client is not None and hasattr(chat_client,'tokenizer'):
            make_messages=configure_budget(adapter,chat_client,question,u,unit,pages,EXTRA_RULES,CONDITION_RULES,
                builder=source_selection.prompt if selecting else None)
        evidence = adapter.from_pages(pages, corpus, qv, unit)
        candidates=source_selection.catalog(evidence,question) if selecting else None
        if selecting and not candidates:evidence={}
        if not evidence or selecting and not source_selection.value_ids(candidates or {}):
            out = {'status':'not_found','items':[],'answer_ko':'이 검색 범위에서 답변에 사용할 근거를 확보하지 못했습니다.'}
            r = {'model_reported':None,'prompt_tokens':0,'completion_tokens':0}
            out = grounded_answer(out, evidence)
        else:
            messages = make_messages(evidence)
            from copy import deepcopy
            schema = condition_schema(SCHEMA)
            if selecting:schema=source_selection.schema(candidates)
            else:
                schema['schema']['properties']['items']['items']['properties']['evidence']['items']['enum'] = list(evidence)
                schema['schema']['properties']['items']['items']['properties']['conditions']['items']['properties']['evidence']['enum']=list(evidence)
            r = (chat_client or chat)(messages,json_schema=schema,provider=provider)
            out = json.loads(r['text'])
            if selecting:out=source_selection.resolve(out,candidates,evidence,question,u)
            else:validate_shape(out)
            out = grounded_answer(out,evidence)
            # One bounded correction uses the identical evidence and schema.
            # Literal checks remain unchanged; no values/citations are repaired
            # by code or silently promoted into source evidence.
            from rag.answer_conditions import attribution_missing, explicit_conflicts
            def condition_gaps(value):
                return attribution_missing(value['items'],evidence,u,missing_conditions(value['items'],question,u))
            initial_gaps=condition_gaps(out)
            if (out['validation']['rejected_items'] or out['validation']['rejected_conditions'] or initial_gaps) and not selecting:
                initial_rejected = out['validation']['rejected_items']
                feedback = ('The previous answer failed literal source checks. Return the complete corrected answer. '
                    'For every item, copy value as ONE contiguous substring of quote, and copy quote verbatim '
                    'from ONE cited evidence block. Use only that block ID. Do not combine separate HTML cells '
                    'or labels, replace semicolons with words, or turn literal backslash-n into a newline. '
                    'Use separate items for a ratio and a confidence interval if they occupy separate cells. '
                    'You may quote a source prose sentence instead when it contains the requested value exactly. '
                    'Omit any item you cannot ground. Keep already supported facts. Rejected items:\n'
                    + json.dumps(initial_rejected, ensure_ascii=False))
                compact=[{k:str(i.get(k,''))[:160] for k in ('source_label','value','reason')} for i in initial_rejected]
                prefix=feedback[:feedback.index('Rejected items:')]+(
                    'Use printed source study names, NEVER ST_* metadata keys. Include cited conditions required '
                    'by the question, with exact source quotations. Preserve dose intervals and route when asked. ')
                problems={'rejected_items':compact,'rejected_conditions':[
                    {k:str(c.get(k,''))[:100] for k in ('dimension','evidence','quote')}
                    for c in out['validation']['rejected_conditions']], 'missing_conditions':initial_gaps}
                feedback=prefix+json.dumps(problems,ensure_ascii=False)
                if hasattr(chat_client,'tokenizer'):
                    while chat_client.tokenizer.messages([*messages,{'role':'user','content':feedback}])>chat_client.input_limit:
                        largest=max(problems,key=lambda k:len(problems[k]))
                        if not problems[largest]:break
                        problems[largest].pop()
                        feedback=prefix+json.dumps(problems,ensure_ascii=False)
                retry_messages = [*messages, {'role': 'user', 'content': feedback}]
                try:
                    if hasattr(chat_client,'tokenizer') and chat_client.tokenizer.messages(retry_messages)>chat_client.input_limit:
                        raise ValueError('Literal repair would exceed reserved input token budget')
                    retried = (chat_client or chat)(retry_messages,json_schema=schema,provider=provider)
                    r = {**r, 'prompt_tokens': r['prompt_tokens'] + retried['prompt_tokens'],
                         'completion_tokens': r['completion_tokens'] + retried['completion_tokens']}
                    corrected = json.loads(retried['text']); validate_shape(corrected)
                    corrected = grounded_answer(corrected,evidence)
                    defects=lambda value:len(value['validation']['rejected_items'])+len(value['validation']['rejected_conditions'])+len(condition_gaps(value))
                    improved = len(corrected['items']) > len(out['items']) or (
                        len(corrected['items'])==len(out['items']) and defects(corrected)<defects(out))
                    if improved:
                        out = corrected
                    out['validation']['repair'] = {'attempts': 1, 'accepted': improved,
                        'initial_rejected_items': initial_rejected,
                        'retry_rejected_items': corrected['validation']['rejected_items']}
                except (ValueError, KeyError, RuntimeError, OSError) as exc:
                    out['validation']['repair'] = {'attempts': 1, 'accepted': False,
                        'initial_rejected_items': initial_rejected, 'error': f'{type(exc).__name__}: {exc}'}
            from rag.regulatory_scope import enforce as enforce_requested_source_scope
            enforce_requested_source_scope(out,evidence,question)
            adapter.attach_quote_links(out,evidence)
            absent=missing_conditions(out['items'],question,u)
            absent=attribution_missing(out['items'],evidence,u,absent)
            out['validation']['missing_conditions']=absent
            if absent and out['items']:
                out['status']='partial'
                for missing in absent:
                    item=out['items'][missing['item_index']]
                    item['unresolved_conditions']=missing['dimensions']
                    item['exact']=False
                out['answer_ko']='\n'.join(f'{condition_label(item)}{" (관련 값)" if not item["exact"] else ""}: '
                    f'{item["value"]} [{", ".join(item["evidence"])}]' for item in out['items'])
            conflicts=explicit_conflicts(out['items'],question,u)
            out['validation']['condition_conflicts']=conflicts
            if conflicts:
                blocked={c['item_index'] for c in conflicts}
                out['items']=[item for i,item in enumerate(out['items']) if i not in blocked]
                out['status']='partial' if out['items'] else 'not_found'
                explanation='요청 조건과 다른 원문 조건이 확인되어 해당 결과값을 답변에서 제외했습니다. '
                explanation+='; '.join(f'{c["dimension"]}: {c["source_quote"]} [{c["evidence"]}]' for c in conflicts)
                out['answer_ko']=explanation+'\n'+'\n'.join(
                    f'{condition_label(item)}: {item["value"]} [{", ".join(item["evidence"])}]' for item in out['items'])
            from rag.answer_conditions import unresolved_scopes
            # Condition gaps are checked on the remaining items after conflicts
            # so the recorded indices cannot remove a different item.
            remaining=attribution_missing(out['items'],evidence,u,missing_conditions(out['items'],question,u))
            withheld=unresolved_scopes(remaining)
            out['validation']['withheld_unresolved_scope_items']=[
                {'item':out['items'][m['item_index']],'missing_dimensions':m['dimensions']} for m in withheld]
            if withheld:
                blocked={m['item_index'] for m in withheld}
                out['items']=[item for i,item in enumerate(out['items']) if i not in blocked]
                out['status']='partial' if out['items'] else 'not_found'
                out['answer_ko']='요청한 시험·분석·비교·용량 조건을 원문으로 확인하지 못한 결과값을 제외했습니다.\n'+'\n'.join(
                    f'{condition_label(item)}: {item["value"]} [{", ".join(item["evidence"])}]' for item in out['items'])
        if selecting:
            from rag.source_context import dose_premise_sources, enforce_comparison_coverage, enforce_arm_coverage
            sources=out.get('premise_sources',[])
            if not out['items'] and not sources:sources=dose_premise_sources(candidates,evidence,question,u)
            premise=source_selection.premise_conflicts(sources,evidence,question,u)
            out['validation']['source_premise_conflicts']=premise
            if premise:
                out['answer_ko']='요청 조건과 다른 원문 조건이 확인됐습니다: '+ '; '.join(
                    f'{condition_label({"source_label":"원문 조건","conditions":[{"dimension":c["dimension"],"value":c["value"]}]})} [{c["evidence"]}]' for c in premise)+ '\n'+out['answer_ko']
            enforce_comparison_coverage(out,candidates or {},question,unit.get('product'))
            enforce_arm_coverage(out,candidates or {},question)
            from rag.dosing_coverage import enforce as enforce_dosing_coverage
            enforce_dosing_coverage(out,candidates or {},evidence,question)
        return {**out,'unit':unit,'evidence':evidence,'model':r['model_reported'],
                'prompt_tokens':r['prompt_tokens'],'completion_tokens':r['completion_tokens'],
                'prompt_version':PROMPT_VERSION+'-'+PREPROCESSED_PROMPT_VERSION,'omitted_chunks':list(adapter.last_omitted),
                'source_selection_version':source_selection.VERSION if selecting else None,
                'context_budget':getattr(adapter,'last_budget',{})}
    texts = [corpus.page_text(p["document_id"], p["pdf_page"], qv, p.get("version_id")) for p in pages]
    provenance = [(p["document_id"], p.get("version_id"), p["pdf_page"], p.get("locations", []), p.get("source_url")) for p in pages]
    key = hashlib.sha256(json.dumps([PROMPT_VERSION, SYSTEM, SCHEMA, sr.REGISTRY.read_text(encoding="utf-8"),
                                    question, u["english_query"], unit, provenance, texts, provider],
                                   ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()
    if cache is not None and key in cache:
        cached = cache[key]
        checked = validate_answer(cached, cached["evidence"])
        old_rejections = cached.get("validation", {}).get("rejected_items", [])
        combined = {json.dumps(it, ensure_ascii=False, sort_keys=True): it for it in [*old_rejections, *checked["validation"]["rejected_items"]]}
        checked["validation"]["rejected_items"] = list(combined.values())
        cache[key] = checked
        return checked
    evidence = {f"E{n}": {"document_id": p["document_id"], "version_id": p.get("version_id"), "pdf_page": p["pdf_page"], "title": p["title"],
                          "also_in": p["also_in"], "locations": p.get("locations", []), "source_url": p.get("source_url"),
                          "evidence_status": "unreviewed_retrieval", "text": t}
                for n, (p, t) in enumerate(zip(pages, texts), 1)}
    if not pages:
        out = {"status": "not_found", "items": [], "answer_ko": "이 기관의 문서에서 검색된 페이지가 없다."}
        r = {"model_reported": None, "prompt_tokens": 0, "completion_tokens": 0}
    else:
        r = (chat_client or chat)(messages_for(question, u, unit, pages, texts), json_schema=SCHEMA, provider=provider)
        out = json.loads(r["text"])
    out = validate_answer(out, evidence)
    res = {**out, "unit": unit, "evidence": evidence, "model": r["model_reported"],
           "prompt_tokens": r["prompt_tokens"], "completion_tokens": r["completion_tokens"], "prompt_version": PROMPT_VERSION}
    if cache is not None:
        cache[key] = res
    return res


def render(results):
    """Korean reply: one section per agency and product, values with document and page citations."""
    lines = []
    for r in results:
        unit = r["unit"]
        head = f"## {AGENCY[unit['jurisdiction']]} · {unit['product']}"
        if unit["studies"]:
            head += " · " + ", ".join(study_context.label([k]) for k in unit["studies"])
        lines += [head, "", r["answer_ko"], ""]
        cited = sorted({e for it in r["items"] for e in it["evidence"]} | set(re.findall(r"E\d+", r["answer_ko"])),
                       key=lambda e: int(e[1:]))
        for e in cited:
            if e in r["evidence"]:
                ev = r["evidence"][e]
                title = f"[{ev['title']}]({ev['source_url']})" if ev.get("source_url") else ev["title"]
                lines.append(f"- [{e}] {title}, p.{ev['pdf_page']}")
                for n,link in enumerate(ev.get('review_links',[]),1):
                    lines.append(f"  [원본 영역 {n} · p.{link['pdf_page']}]({link['url']})")
        lines.append("")
    return "\n".join(lines)


